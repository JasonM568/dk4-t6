-- 場次「固定組數」：實體場地的桌次是固定的，組數不該隨報名人數自己長。
--
-- 現行組數是推導出來的：max(6, ⌈有效人數 ÷ 每組上限⌉)，人一多就自動開新組、
-- 沒有天花板。場地只有 8 張桌子時系統分出 9 組，名單就跟現場對不起來，
-- 管理員得手動把第 9 組的人一個個搬回去。
--
-- NULL = 沿用現行自動推導（至少 6 組），既有場次行為完全不變。
-- 有值時組數鎖死為該值，且優先於「至少 6 組」的下限（小場次可以只開 4 組）；
-- 人數塞不下時由 action 擋下並報錯，不默默超收、也不默默把人丟掉。
--
-- 限於 course schema；不觸碰 public / auth。純新增欄位，不動既有資料。

